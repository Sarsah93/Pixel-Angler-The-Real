export interface HelpKey { key: string; desc: string }

export interface HelpPage {
  heading: string;
  /** 문단 배열 — 문단마다 wordWrap */
  body: string[];
  /** 실캡처 텍스처 키 (help_*) — 없으면 프레임만 */
  image?: string;
  imageCaption?: string;
  tips?: string[];
  /** 단축키 표 (key 칩 + 설명) */
  keys?: HelpKey[];
}

export interface HelpTopic {
  id: string;
  label: string;
  pages: HelpPage[];
  status?: 'ready' | 'planned';
}

export interface HelpSection { id: string; label: string; topics: HelpTopic[] }
export interface HelpCategory { id: string; label: string; sections: HelpSection[] }

