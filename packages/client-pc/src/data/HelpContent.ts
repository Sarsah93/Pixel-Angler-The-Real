/** 토픽 id로 조회 (카테고리·섹션 경로 포함) */
export function findHelpTopic(id: string): { cat: HelpCategory; sec: HelpSection; topic: HelpTopic } | null {
  for (const cat of HELP_LIBRARY) for (const sec of cat.sections) for (const topic of sec.topics) {
    if (topic.id === id) return { cat, sec, topic };
  }
  return null;
}
