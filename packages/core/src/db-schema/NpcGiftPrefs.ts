/** 취향 표 조회 */
export function giftPrefOf(npcId: string): (NpcGiftPrefDef & { home?: string }) | undefined {
  return NPC_GIFT_PREFS.find((p) => p.npcId === npcId);
}

/** 그 사람의 고향 지역(WorldMap 지역 id) — 표의 `home` → 아크 지역 → 주역(속초) */
export function giftHomeRegionOf(npcId: string): string | undefined {
  const pref = giftPrefOf(npcId);
  if (pref?.home) return pref.home;
  const arc = STORY_ARCS.find((a) => a.npcs.some((n) => n.id === npcId));
  if (arc) return arc.regionId;
  return STORY_MAIN_NPCS.some((n) => n.id === npcId) ? 'gangwon_sokcho' : undefined;
}

