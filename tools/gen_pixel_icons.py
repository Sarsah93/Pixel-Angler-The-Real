"""
@file gen_pixel_icons.py
@description HUD 픽셀 아이콘 아트 -> packages/client-pc/src/data/PixelIconArt.ts 자동 생성 (128차)

상태이상 11종 + 생존 지표 2종(허기·수분)을 **16x16 손그림 픽셀 매트릭스**로 보관한다.
문자 = 팔레트 인덱스, '.' = 투명. 여기서 art를 고치고 다시 실행하면 TS가 갱신된다.

    py tools/gen_pixel_icons.py

⚠ 규칙: 도형 프리미티브 조합(원+사각)이 아니라 **픽셀 단위 손그림**이다.
   행 길이는 스크립트가 검사하므로(16자 고정) 어긋나면 바로 에러가 난다.
"""
import io, os, sys

W = H = 16

ICONS = {}

def icon(key, pal, art):
    rows = [r for r in art.strip('\n').split('\n')]
    if len(rows) != H:
        raise SystemExit(f'{key}: 행 수 {len(rows)} != {H}')
    for i, r in enumerate(rows):
        if len(r) != W:
            raise SystemExit(f'{key}: r{i} 길이 {len(r)} != {W} -> "{r}"')
        for ch in r:
            if ch != '.' and ch not in pal:
                raise SystemExit(f'{key}: r{i} 팔레트에 없는 문자 "{ch}"')
    ICONS[key] = (pal, rows)

