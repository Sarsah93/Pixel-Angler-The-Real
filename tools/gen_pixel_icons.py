out.write('/**\n')
out.write(' * @file PixelIconArt.ts\n')
out.write(' * @description HUD 픽셀 아이콘 아트 (자동 생성 — 수동 편집 금지)\n')
out.write(' *\n')
out.write(' * 생성기: `py tools/gen_pixel_icons.py` (아트 원본도 그 안에 있다)\n')
out.write(' * 16x16 손그림 매트릭스 — 문자 = 팔레트 키, `.` = 투명.\n')
out.write(' * 굽기·렌더는 `ui/PixelIcon.ts`가 담당한다(여기는 순수 데이터).\n')
out.write(' */\n\n')
out.write('export interface PixelIconArt {\n')
out.write('  /** 가로 픽셀 수 */\n  w: number;\n')
out.write('  /** 세로 픽셀 수 */\n  h: number;\n')
out.write('  /** 팔레트 — 문자 → 0xRRGGBB */\n  pal: Record<string, number>;\n')
out.write('  /** 행 배열 (길이 = h, 각 행 길이 = w) */\n  rows: string[];\n')
out.write('}\n\n')
out.write('export const PIXEL_ICON_ART: Record<string, PixelIconArt> = {\n')
for key, (pal, rows) in ICONS.items():
    out.write(f"  {key}: {{\n    w: {W}, h: {H},\n    pal: {{ ")
    out.write(', '.join(f"'{c}': 0x{v:06x}" for c, v in pal.items()))
    out.write(' },\n    rows: [\n')
    for r in rows:
        out.write(f"      '{r}',\n")
    out.write('    ],\n  },\n')
out.write('};\n\n')
out.write('/** 아이콘 키 유니온 — 상태이상 badge.icon / 지표 아이콘이 이 키를 참조한다 */\n')
out.write('export type PixelIconKey = keyof typeof PIXEL_ICON_ART;\n')

dst = os.path.join('packages', 'client-pc', 'src', 'data', 'PixelIconArt.ts')
with open(dst, 'w', encoding='utf-8') as f:
    f.write(out.getvalue())
print(f'생성: {dst} — 아이콘 {len(ICONS)}종')
