TEMPLATES = {}

def template(name, art):
    rows = art.strip('\n').split('\n')
    if len(rows) != W:
        raise SystemExit(f'template {name}: 행 수 {len(rows)} != {W}')
    for i, r in enumerate(rows):
        if len(r) != W:
            raise SystemExit(f'template {name}: r{i} 길이 {len(r)} != {W} -> "{r}"')
    TEMPLATES[name] = rows

def icon_t(key, tname, pal):
    """원형 `tname`에 팔레트 `pal`을 입힌 아이콘 — 원형이 쓰는 문자가 팔레트에 다 있어야 한다"""
    rows = TEMPLATES[tname]
    for i, r in enumerate(rows):
        for ch in r:
            if ch != '.' and ch not in pal:
                raise SystemExit(f'{key}({tname}): r{i} 팔레트에 없는 문자 "{ch}"')
    used = {ch for r in rows for ch in r if ch != '.'}
    ICONS[key] = ({k: v for k, v in pal.items() if k in used}, rows, W, W, tname)

