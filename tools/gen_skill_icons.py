def syn(key, motif, pal=None):
    """시너지 엠블럼: 공용 금테 위에 motif 를 얹어 16x16 아트를 만든다."""
    frame = SYN_FRAME.strip('\n').split('\n')
    mrows = motif.strip('\n').split('\n')
    if len(mrows) != H:
        raise SystemExit(f'{key}: motif 행 수 {len(mrows)} != {H}')
    out = []
    for i, (fr, mr) in enumerate(zip(frame, mrows)):
        if len(mr) != W:
            raise SystemExit(f'{key}: motif r{i} 길이 {len(mr)} != {W} -> "{mr}"')
        out.append(''.join(m if m != '.' else f for f, m in zip(fr, mr)))
    icon(key, '\n'.join(out), pal)


