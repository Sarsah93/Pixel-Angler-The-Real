def build_ts():
    out = io.StringIO()
    out.write('/**\n')
    out.write(' * @file SkillIconArt.ts\n')
    out.write(' * @description 스킬 트리 아이콘 아트 (자동 생성 — 수동 편집 금지)\n')
    out.write(' *\n')
    out.write(' * 생성기: `py tools/gen_skill_icons.py` (아트 원본도 그 안에 있다)\n')
    out.write(f' * 스킬 {len(ICONS)}종 × 16x16 손그림 매트릭스 — 키 = 스킬 id, 문자 = 팔레트 키, `.` = 투명.\n')
    out.write(' * 숨은 시너지(syn_*)는 공용 금테 엠블럼 위에 그림을 얹는다.\n')
    out.write(' * 굽기·렌더는 `ui/PixelIcon.ts`와 같은 방식으로 한다(여기는 순수 데이터).\n')
    out.write(' */\n\n')
    out.write("import type { PixelIconArt } from './PixelIconArt.js';\n\n")
    out.write('/** 스킬 id → 16x16 픽셀 아이콘 */\n')
    out.write('export const SKILL_ICON_ART: Record<string, PixelIconArt> = {\n')
    for key in SKILL_IDS:
        pal, rows, w, h = ICONS[key]
        out.write(f"  {key}: {{\n    w: {w}, h: {h},\n    pal: {{ ")
        out.write(', '.join(f"'{c}': 0x{v:06x}" for c, v in pal.items()))
        out.write(' },\n    rows: [\n')
        for r in rows:
            out.write(f"      '{r}',\n")
        out.write('    ],\n  },\n')
    out.write('};\n')
    return out.getvalue()


