import io, os, sys

W = H = 16

# ── 공용 팔레트 ─────────────────────────────────────────
PAL = {
    'o': 0x1a1c24,  # 윤곽
    'w': 0xffffff,  # 하이라이트 흰색
    'G': 0xd0d8e0,  # 밝은 회색
    'g': 0x8c98a4,  # 회색
    'd': 0x4c5864,  # 어두운 회색
    'b': 0x6e4420,  # 어두운 갈색
    'B': 0xa8702e,  # 갈색
    'n': 0xdcae66,  # 황갈(나무 밝은면)
    'u': 0x2464a8,  # 짙은 파랑
    'U': 0x4aa0e0,  # 파랑
    'c': 0xa8e0f8,  # 밝은 하늘
    'r': 0xa82a22,  # 짙은 빨강
    'R': 0xe8503a,  # 빨강
    'y': 0xe8b030,  # 금색
    'Y': 0xffe486,  # 밝은 금색
    'k': 0x9a6c18,  # 짙은 금색
    'e': 0x2e7a34,  # 짙은 초록
    'E': 0x5cb84a,  # 초록
    'l': 0xb4e47a,  # 연두
    'v': 0x3a2c70,  # 남보라(밤)
    'V': 0x6c5cc0,  # 보라
    'a': 0xd86a1c,  # 주황
    'A': 0xf8b060,  # 밝은 주황
    's': 0xf2c294,  # 피부
    'S': 0xc4865a,  # 피부 그늘
    'm': 0xf0e8d0,  # 종이(크림)
    'M': 0xc8b890,  # 종이 그늘
    'p': 0xf08cb0,  # 분홍
    'P': 0xb04a78,  # 짙은 분홍
}

ICONS = {}


def icon(key, art, pal=None):
    """16x16 아이콘 등록. pal 로 공용 팔레트 문자를 덮어쓰거나 추가한다."""
    full = dict(PAL)
    full.update(pal or {})
    rows = [r for r in art.strip('\n').split('\n')]
    if len(rows) != H:
        raise SystemExit(f'{key}: 행 수 {len(rows)} != {H}')
    used = []
    for i, r in enumerate(rows):
        if len(r) != W:
            raise SystemExit(f'{key}: r{i} 길이 {len(r)} != {W} -> "{r}"')
        for j, ch in enumerate(r):
            if ch == '.':
                continue
            if ch not in full:
                raise SystemExit(f'{key}: r{i} 팔레트에 없는 문자 "{ch}"')
            if i in (0, H - 1) or j in (0, W - 1):
                raise SystemExit(f'{key}: r{i} c{j} 가장자리 1px 여백 침범 -> "{r}"')
            if ch not in used:
                used.append(ch)
    if len(used) > 8:
        raise SystemExit(f'{key}: 색 {len(used)}개 — 윤곽 포함 8색 이하로')
    if key in ICONS:
        raise SystemExit(f'{key}: 중복 등록')
    ICONS[key] = ({c: full[c] for c in sorted(used)}, rows, W, H)


